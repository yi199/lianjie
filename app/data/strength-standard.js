/**
 * 力量水平标准表（设计文档 §8）
 *
 * 口径：倍体重 = 估算 1RM ÷ 体重，对照一张「几倍体重算几档」的表，
 * 给出 新手 → 入门 → 中级 → 进阶 → 精英 五档。
 *
 * ⚠️ 数据来源说明（写进界面上，别藏着）：
 *   这里的档位是按公开力量标准表（Strength Level / ExRx 一类）的常见中位数取整，
 *   **不是同行评审研究**。所以界面必须标「仅供参考」，以后由专业体系替换数据源。
 * ⚠️ 只对 5 个标准动作评级：卧推 / 深蹲 / 硬拉 / 推举 / 引体。
 *   其它动作（哑铃、器械、绳索）重量口径不一样，硬凑会给出误导性的评级。
 * ⚠️ 引体是自重动作：负荷 = 体重 × 系数 + 额外负重 - 助力，
 *   所以「倍体重」约等于 1 + 额外负重 / 体重，1.0 就是「标准自重引体」。
 *
 * 档位取值得注意的一条：**1 倍体重卧推 ≈ 中级偏上，不是进阶**。
 * 进阶通常要 1.2 倍以上（深蹲 1.75、硬拉 2.0），所以门槛别定得太松，
 * 否则随便练两个月就「进阶」，评级就没有参考价值了。
 */

const LEVELS = ['新手', '入门', '中级', '进阶', '精英'];

/** thresholds: [入门, 中级, 进阶, 精英] 四个门槛（倍体重） */
const LIFTS = [
  { exId: 'g1',  cn: '卧推', m: [0.50, 0.85, 1.20, 1.50], f: [0.25, 0.45, 0.65, 0.85], bw: false },
  { exId: 'g40', cn: '深蹲', m: [0.75, 1.25, 1.75, 2.25], f: [0.50, 0.90, 1.30, 1.60], bw: false },
  { exId: 'g42', cn: '硬拉', m: [1.00, 1.50, 2.00, 2.50], f: [0.60, 1.00, 1.50, 1.90], bw: false },
  { exId: 'g32', cn: '推举', m: [0.35, 0.55, 0.80, 1.00], f: [0.20, 0.35, 0.50, 0.65], bw: false },
  { exId: 'g5',  cn: '引体', m: [0.90, 1.00, 1.20, 1.40], f: [0.80, 0.95, 1.10, 1.25], bw: true }
];

/** 某个动作、某个性别对应的四个门槛；sex 只认 'm' / 'f' */
function thresholdsOf(exId, sex) {
  const lift = LIFTS.filter(function (x) { return x.exId === exId; })[0];
  if (!lift) return null;
  return sex === 'f' ? lift.f : lift.m;
}

function liftOf(exId) {
  return LIFTS.filter(function (x) { return x.exId === exId; })[0] || null;
}

module.exports = { LEVELS, LIFTS, thresholdsOf, liftOf };
